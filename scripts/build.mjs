#!/usr/bin/env node
/**
 * Build index.js from src/index.ts with Node's built-in type stripper.
 *
 * Same contract as the sibling packages: ONE shipped file, no runtime relative imports.
 * This package has a single source file, so the composer is deliberately simple — when a
 * second module appears, copy dsh-graft-slice/scripts/bundle.mjs instead of growing this.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { stripTypeScriptTypes } from 'node:module'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = readFileSync(join(root, 'src', 'index.ts'), 'utf8')

if (/from\s+'\.\//u.test(source)) {
  throw new Error('src/index.ts has a relative import: use the bundler from dsh-graft-slice/scripts instead')
}

const banner = '// GENERATED from src/index.ts by scripts/build.mjs — do not edit this file directly.\n'
const output = banner + stripTypeScriptTypes(source, { mode: 'strip' })
writeFileSync(join(root, 'index.js'), output, 'utf8')
process.stdout.write(`built index.js (${Buffer.byteLength(output)} bytes)\n`)

/**
 * The Client half is plain ESM and is served as `client.js` — no copy, no versioned file.
 * v0.1.14 shipped `client-v14.js` plus a versioned module id and the next start died with
 * `Web authentication failed`; the client entry and its specifier stay exactly where the
 * sibling plugins keep them.
 */
const client = readFileSync(join(root, 'client.js'), 'utf8')
if (/id:\s*'dsh-observer-v/u.test(client)) {
  throw new Error('client.js must register with the plain id `dsh-observer` — a versioned id broke Web auth')
}
process.stdout.write(`client.js ${Buffer.byteLength(client)} bytes (plain id, no polling)\n`)
